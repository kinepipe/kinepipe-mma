from fastapi import APIRouter, UploadFile, File, HTTPException, Response
from fastapi.responses import FileResponse
from pathlib import Path
import shutil
import uuid
import cv2
from typing import List, Optional, Dict

from ..core.config import UPLOADS_DIR, SAMPLE_DIR
from ..core.schemas import VideoMetadata
from ..core.video_engine import (
    get_video_metadata,
    save_frame_thumbnail,
    generate_sample_biomechanical_video,
    extract_frame_image
)

router = APIRouter(prefix="/api/video", tags=["video"])

@router.post("/upload", response_model=VideoMetadata)
async def upload_video(file: UploadFile = File(...)):
    """
    Uploads a video, calculates its technical metadata and generates a thumbnail.
    """
    ext = Path(file.filename).suffix.lower()
    if ext not in [".mp4", ".mov", ".avi", ".mkv", ".webm"]:
        raise HTTPException(status_code=400, detail="Formato de video no soportado. Use MP4, MOV o AVI.")

    video_id = str(uuid.uuid4())[:8]
    saved_filename = f"{video_id}_{file.filename}"
    target_path = UPLOADS_DIR / saved_filename

    with open(target_path, "wb") as buffer:
        shutil.copyfileobj(file.file, buffer)

    metadata = get_video_metadata(target_path)
    
    # Generate thumbnail for frame 0
    thumb_path = UPLOADS_DIR / f"{video_id}_thumb.jpg"
    save_frame_thumbnail(target_path, 0, thumb_path)
    
    return metadata

@router.get("/sample", response_model=VideoMetadata)
def get_or_create_sample_video():
    """
    Retrieves or generates a synthetic Countermovement Jump (CMJ) video
    with a 1-meter calibration stick for instant experimentation.
    """
    sample_path = SAMPLE_DIR / "sample_cmj_jump.mp4"
    if not sample_path.exists():
        generate_sample_biomechanical_video(sample_path, duration_s=3.0, fps=30.0)

    metadata = get_video_metadata(sample_path)
    
    # Generate thumbnail
    thumb_path = SAMPLE_DIR / "sample_cmj_thumb.jpg"
    if not thumb_path.exists():
        save_frame_thumbnail(sample_path, 0, thumb_path)
        
    return metadata

@router.get("/list", response_model=List[VideoMetadata])
def list_videos():
    """
    Lists all available videos in uploads and sample directories.
    """
    videos = []
    for f in list(UPLOADS_DIR.iterdir()) + list(SAMPLE_DIR.iterdir()):
        if f.suffix.lower() in [".mp4", ".mov", ".avi", ".webm"]:
            try:
                videos.append(get_video_metadata(f))
            except Exception:
                pass
    return videos

@router.get("/{video_id}/stream")
def stream_video(video_id: str):
    """
    Serves the video file for HTML5 video playback.
    """
    matches = list(UPLOADS_DIR.glob(f"{video_id}*")) + list(SAMPLE_DIR.glob(f"{video_id}*"))
    video_matches = [m for m in matches if m.suffix.lower() in [".mp4", ".mov", ".avi", ".webm"]]
    
    if not video_matches:
        # Check if sample video matches
        sample_path = SAMPLE_DIR / "sample_cmj_jump.mp4"
        if sample_path.exists():
            return FileResponse(str(sample_path), media_type="video/mp4")
        raise HTTPException(status_code=404, detail="Video no encontrado")

    return FileResponse(str(video_matches[0]), media_type="video/mp4")

@router.get("/{video_id}/thumbnail")
def get_thumbnail(video_id: str):
    matches = list(UPLOADS_DIR.glob(f"{video_id}*_thumb.jpg")) + list(SAMPLE_DIR.glob(f"{video_id}*_thumb.jpg"))
    if matches:
        return FileResponse(str(matches[0]), media_type="image/jpeg")
    
    # Try sample thumbnail
    sample_thumb = SAMPLE_DIR / "sample_cmj_thumb.jpg"
    if sample_thumb.exists():
        return FileResponse(str(sample_thumb), media_type="image/jpeg")
        
    raise HTTPException(status_code=404, detail="Miniatura no encontrada")

@router.get("/{video_id}/frame/{frame_index}")
def get_frame_image(video_id: str, frame_index: int):
    """
    Returns an optimized JPEG thumbnail for any frame in the video.
    Used for autogenerated and manual keyframe snapshots.
    """
    matches = list(UPLOADS_DIR.glob(f"{video_id}*")) + list(SAMPLE_DIR.glob(f"{video_id}*"))
    video_matches = [m for m in matches if m.suffix.lower() in [".mp4", ".mov", ".avi", ".webm"]]
    if not video_matches:
        sample_path = SAMPLE_DIR / "sample_cmj_jump.mp4"
        if sample_path.exists():
            video_matches = [sample_path]
        else:
            raise HTTPException(status_code=404, detail="Video no encontrado")

    video_path = video_matches[0]
    frame = extract_frame_image(video_path, frame_index)
    if frame is None:
        raise HTTPException(status_code=404, detail="Fotograma no disponible")

    # Downscale for performance (max width 480px)
    h, w = frame.shape[:2]
    max_w = 480
    if w > max_w:
        scale = max_w / float(w)
        frame = cv2.resize(frame, (max_w, int(h * scale)), interpolation=cv2.INTER_AREA)

    ret, buf = cv2.imencode(".jpg", frame, [cv2.IMWRITE_JPEG_QUALITY, 80])
    if not ret:
        raise HTTPException(status_code=500, detail="Error codificando imagen")

    return Response(content=buf.tobytes(), media_type="image/jpeg")
